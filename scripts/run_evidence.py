#!/usr/bin/env python3
"""Run the repair-loop evidence experiment."""

from __future__ import annotations

import csv
import json
import statistics
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from repair_loop_sim import make_env, prediction_error, run_episode, strategy_factory  # noqa: E402


RESULTS = ROOT / "results"
FIGURES = ROOT / "paper" / "figures"
DOCS = ROOT / "docs"

STRATEGIES = [
    "nominal_no_repair",
    "prediction_gated_repair",
    "ccra_exact_guard",
    "ccra_row_guard",
    "oracle_fault_model",
]

DISPLAY = {
    "nominal_no_repair": "Nominal, no repair",
    "prediction_gated_repair": "Prediction-gated repair",
    "ccra_exact_guard": "CCRA exact guard",
    "ccra_row_guard": "CCRA row guard",
    "oracle_fault_model": "Oracle fault model",
}


def mean(values: list[float]) -> float:
    return statistics.fmean(values) if values else 0.0


def run(seed_count: int = 80, episodes: int = 5) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    trial_rows: list[dict[str, object]] = []
    summary_rows: list[dict[str, object]] = []

    for strategy in STRATEGIES:
        first_success: list[float] = []
        all_success: list[float] = []
        first_mismatches: list[float] = []
        all_mismatches: list[float] = []
        first_steps: list[float] = []
        initial_losses: list[float] = []
        final_losses: list[float] = []

        for seed in range(seed_count):
            env = make_env(seed)
            model = strategy_factory(strategy)
            initial_loss = prediction_error(env, model)
            initial_losses.append(initial_loss)
            for episode in range(episodes):
                out = run_episode(env, model)
                row = {
                    "seed": seed,
                    "strategy": strategy,
                    "episode": episode,
                    "success": int(bool(out["success"])),
                    "steps": int(out["steps"]),
                    "mismatches": int(out["mismatches"]),
                    "replans": int(out["replans"]),
                    "fault_edges": len(env.fault_edges),
                    "initial_prediction_error": initial_loss,
                }
                trial_rows.append(row)
                all_success.append(float(row["success"]))
                all_mismatches.append(float(row["mismatches"]))
                if episode == 0:
                    first_success.append(float(row["success"]))
                    first_mismatches.append(float(row["mismatches"]))
                    first_steps.append(float(row["steps"]))
            final_losses.append(prediction_error(env, model))

        summary_rows.append(
            {
                "strategy": strategy,
                "display": DISPLAY[strategy],
                "first_episode_success_rate": mean(first_success),
                "all_episode_success_rate": mean(all_success),
                "mean_first_episode_counterexamples": mean(first_mismatches),
                "mean_counterexamples_per_episode": mean(all_mismatches),
                "mean_first_episode_steps": mean(first_steps),
                "mean_initial_prediction_error": mean(initial_losses),
                "mean_final_prediction_error": mean(final_losses),
                "median_final_prediction_error": statistics.median(final_losses),
            }
        )
    return trial_rows, summary_rows


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    if not rows:
        return
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_latex_table(summary_rows: list[dict[str, object]]) -> None:
    lines = [
        "% Auto-generated by scripts/run_evidence.py",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Method & First success $\\uparrow$ & Counterexamples $\\downarrow$ & Final pred. error $\\downarrow$ & All success $\\uparrow$ \\\\",
        "\\midrule",
    ]
    for row in summary_rows:
        lines.append(
            "{display} & {first:.2f} & {ce:.1f} & {err:.3f} & {alls:.2f} \\\\".format(
                display=row["display"],
                first=float(row["first_episode_success_rate"]),
                ce=float(row["mean_first_episode_counterexamples"]),
                err=float(row["mean_final_prediction_error"]),
                alls=float(row["all_episode_success_rate"]),
            )
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    (FIGURES / "results_table.tex").write_text("\n".join(lines), encoding="utf-8")


def write_svg(summary_rows: list[dict[str, object]]) -> None:
    width = 920
    height = 420
    margin_left = 180
    bar_h = 24
    gap = 24
    top = 64
    colors = {
        "nominal_no_repair": "#444444",
        "prediction_gated_repair": "#1b6ca8",
        "ccra_exact_guard": "#2a9d55",
        "ccra_row_guard": "#b45f06",
        "oracle_fault_model": "#6a4c93",
    }
    max_ce = max(float(r["mean_first_episode_counterexamples"]) for r in summary_rows)
    max_err = max(float(r["mean_final_prediction_error"]) for r in summary_rows)
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        '<text x="28" y="32" font-family="Arial" font-size="20" font-weight="700">Repair loops trade prediction loss for fewer repeated model exploits</text>',
        '<text x="28" y="54" font-family="Arial" font-size="13" fill="#555">Bars show first-episode counterexamples; labels show final full-transition prediction error and success.</text>',
    ]
    for i, row in enumerate(summary_rows):
        y = top + i * (bar_h + gap)
        ce = float(row["mean_first_episode_counterexamples"])
        err = float(row["mean_final_prediction_error"])
        succ = float(row["first_episode_success_rate"])
        bar_w = 1 if max_ce == 0 else int((width - margin_left - 220) * ce / max_ce)
        color = colors[str(row["strategy"])]
        lines.extend(
            [
                f'<text x="28" y="{y + 17}" font-family="Arial" font-size="13">{row["display"]}</text>',
                f'<rect x="{margin_left}" y="{y}" width="{bar_w}" height="{bar_h}" fill="{color}"/>',
                f'<text x="{margin_left + bar_w + 8}" y="{y + 17}" font-family="Arial" font-size="13">{ce:.1f} exploits, pred err {err:.3f}, success {succ:.2f}</text>',
            ]
        )
    axis_y = top + len(summary_rows) * (bar_h + gap) + 10
    lines.extend(
        [
            f'<line x1="{margin_left}" y1="{axis_y}" x2="{width - 220}" y2="{axis_y}" stroke="#222"/>',
            f'<text x="{margin_left}" y="{axis_y + 20}" font-family="Arial" font-size="12">0</text>',
            f'<text x="{width - 260}" y="{axis_y + 20}" font-family="Arial" font-size="12">{max_ce:.1f} mean first-episode counterexamples</text>',
            f'<text x="28" y="{height - 24}" font-family="Arial" font-size="12" fill="#555">Maximum final prediction error in this run: {max_err:.3f}. The broad CCRA row guard intentionally over-repairs but still reaches the goal.</text>',
            "</svg>",
        ]
    )
    (RESULTS / "repair_loop_results.svg").write_text("\n".join(lines), encoding="utf-8")


def write_report(summary_rows: list[dict[str, object]], seed_count: int, episodes: int) -> None:
    lookup = {str(r["strategy"]): r for r in summary_rows}
    nominal = lookup["nominal_no_repair"]
    exact = lookup["ccra_exact_guard"]
    row_guard = lookup["ccra_row_guard"]
    gated = lookup["prediction_gated_repair"]
    lines = [
        "# Evidence Report",
        "",
        f"Ran `{seed_count}` seeded sparse-contact grid worlds with `{episodes}` deployment episodes per method. The nominal model knows grid boundaries but not sparse one-way contact failures on the shortest route. Each episode repeatedly plans with the current model, executes the first action, and lets the method update from observed contradictions.",
        "",
        "## Main Result",
        f"- Nominal no-repair first-episode success: {float(nominal['first_episode_success_rate']):.2f}; mean first-episode counterexamples: {float(nominal['mean_first_episode_counterexamples']):.1f}; final prediction error: {float(nominal['mean_final_prediction_error']):.3f}.",
        f"- Prediction-gated repair first-episode success: {float(gated['first_episode_success_rate']):.2f}; mean first-episode counterexamples: {float(gated['mean_first_episode_counterexamples']):.1f}; final prediction error: {float(gated['mean_final_prediction_error']):.3f}.",
        f"- CCRA exact first-episode success: {float(exact['first_episode_success_rate']):.2f}; mean first-episode counterexamples: {float(exact['mean_first_episode_counterexamples']):.1f}; final prediction error: {float(exact['mean_final_prediction_error']):.3f}.",
        f"- CCRA row-guard first-episode success: {float(row_guard['first_episode_success_rate']):.2f}; mean first-episode counterexamples: {float(row_guard['mean_first_episode_counterexamples']):.1f}; final prediction error: {float(row_guard['mean_final_prediction_error']):.3f}.",
        "",
        "## Interpretation",
        "The nominal model has low average transition error because the faults are sparse, but the planner repeatedly selects the false shortcut and fails. Immediate repair changes the planner-facing model after the first contradiction. The row-guard variant deliberately makes a broader patch: it can have worse full-transition prediction error than the nominal model while still solving the task, illustrating that prediction quality and embodied usefulness can diverge.",
        "",
        "## Files",
        "- `results/evidence_trials.csv`",
        "- `results/evidence_summary.json`",
        "- `results/repair_loop_results.svg`",
        "- `paper/figures/results_table.tex`",
    ]
    (DOCS / "evidence_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    seed_count = 80
    episodes = 5
    RESULTS.mkdir(exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    trial_rows, summary_rows = run(seed_count=seed_count, episodes=episodes)
    write_csv(RESULTS / "evidence_trials.csv", trial_rows)
    write_csv(RESULTS / "evidence_summary.csv", summary_rows)
    (RESULTS / "evidence_summary.json").write_text(
        json.dumps(
            {
                "seed_count": seed_count,
                "episodes_per_method": episodes,
                "summary": summary_rows,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    write_latex_table(summary_rows)
    write_svg(summary_rows)
    write_report(summary_rows, seed_count, episodes)
    print(json.dumps({"summary": summary_rows}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
